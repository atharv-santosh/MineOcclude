"""Build deterministic Person A Phase 3 Wave 2 CPU fixtures.

The action matrix is generated by executing the pinned external MCDataset
converter.  Expected token IDs are never assigned by this project.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
from pathlib import Path
from typing import Any, Sequence

from mineocclude.contracts.identity import SCHEMA_VERSION
from mineocclude.models._mineworld_adapter_wave2 import (
    ACTION_CONVERTER_IDENTITY,
    ACTION_POSITIONAL_ROLES,
    ACTION_VOCABULARY_OFFSET,
    MCDATASET_BLOB_SHA256,
    MINEWORLD_PREPROCESS_BLOB_SHA256,
    PINNED_SOURCE_REVISION,
    PREPROCESSING_PROFILE,
    _OfficialActionConverter,
    _preprocess_bgr_frame,
)
from mineocclude.models.phase2_evidence import (
    VIDEO_PREPROCESSING_NORMALIZATION,
    canonical_json_bytes,
)


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser()
    parser.add_argument("--mineworld-source-root", type=Path, required=True)
    parser.add_argument("--action-output", type=Path, required=True)
    parser.add_argument("--preprocess-output", type=Path, required=True)
    return parser


def _raw_action(
    *,
    keys: Sequence[str] = (),
    dx: float = 0.0,
    dy: float = 0.0,
    buttons: Sequence[int] = (),
) -> dict[str, Any]:
    return {
        "keyboard": {"keys": list(keys)},
        "mouse": {
            "dx": dx,
            "dy": dy,
            "buttons": list(buttons),
        },
    }


def _action_cases() -> tuple[tuple[str, dict[str, Any]], ...]:
    return (
        ("no_op", _raw_action()),
        ("forward", _raw_action(keys=("key.keyboard.w",))),
        ("backward", _raw_action(keys=("key.keyboard.s",))),
        ("left", _raw_action(keys=("key.keyboard.a",))),
        ("right", _raw_action(keys=("key.keyboard.d",))),
        ("jump", _raw_action(keys=("key.keyboard.space",))),
        ("sneak", _raw_action(keys=("key.keyboard.left.shift",))),
        ("sprint", _raw_action(keys=("key.keyboard.left.control",))),
        ("camera_yaw", _raw_action(dx=12.0)),
        ("camera_pitch", _raw_action(dy=-8.0)),
        ("combined_camera", _raw_action(dx=12.0, dy=-8.0)),
        ("hotbar_selection", _raw_action(keys=("key.keyboard.4",))),
        ("attack", _raw_action(buttons=(0,))),
        ("use", _raw_action(buttons=(1,))),
        ("drop", _raw_action(keys=("key.keyboard.q",))),
        ("pick", _raw_action(buttons=(2,))),
        (
            "opposing_direction",
            _raw_action(
                keys=(
                    "key.keyboard.w",
                    "key.keyboard.s",
                    "key.keyboard.a",
                    "key.keyboard.d",
                )
            ),
        ),
        (
            "representative_multi_action",
            _raw_action(
                keys=(
                    "key.keyboard.w",
                    "key.keyboard.space",
                    "key.keyboard.left.control",
                ),
                dx=4.0,
                dy=3.0,
                buttons=(0,),
            ),
        ),
        (
            "one_tick_causal_impulse",
            _raw_action(keys=("key.keyboard.d",), dx=1.0),
        ),
    )


def _source_revision(source_root: Path) -> str:
    result = subprocess.run(
        ["git", "-C", str(source_root), "rev-parse", "HEAD"],
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout.strip()


def _golden_source_frame() -> Any:
    import numpy as np

    y, x = np.indices((360, 640), dtype=np.uint16)
    return np.stack(
        (
            (x + 2 * y) % 256,
            (3 * x + y) % 256,
            np.bitwise_xor(x, y) % 256,
        ),
        axis=2,
    ).astype(np.uint8)


def _write_json(path: Path, value: Any) -> None:
    if path.exists():
        raise FileExistsError(f"Refusing to overwrite fixture: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(
            value,
            sort_keys=True,
            indent=2,
            ensure_ascii=False,
            allow_nan=False,
        )
        + "\n",
        encoding="utf-8",
        newline="\n",
    )


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    source_root = args.mineworld_source_root.resolve()
    observed_revision = _source_revision(source_root)
    if observed_revision != PINNED_SOURCE_REVISION:
        raise RuntimeError(
            f"Expected source {PINNED_SOURCE_REVISION}, observed {observed_revision}"
        )

    converter = _OfficialActionConverter(source_root)
    matrix_cases = []
    for case_id, raw_action in _action_cases():
        normalized, tokens, is_noop = converter.convert(raw_action)
        matrix_cases.append(
            {
                "case_id": case_id,
                "is_noop": is_noop,
                "normalized_action": normalized,
                "raw_action": raw_action,
                "token_ids": list(tokens),
            }
        )
    action_document = {
        "schema_version": SCHEMA_VERSION,
        "fixture_version": "person-a-phase3-action-matrix-v1.0",
        "source_revision": PINNED_SOURCE_REVISION,
        "source_file": "mcdataset.py",
        "source_blob_sha256": MCDATASET_BLOB_SHA256,
        "converter_identity": ACTION_CONVERTER_IDENTITY,
        "vocabulary_offset": ACTION_VOCABULARY_OFFSET,
        "positional_roles": list(ACTION_POSITIONAL_ROLES),
        "generation_method": (
            "Executed pinned MCDataset.json_action_to_env_action followed by "
            "MCDataset.get_action_index_from_actiondict; no expected token "
            "ID was assigned by MineOcclude."
        ),
        "cases": matrix_cases,
    }

    source_frame = _golden_source_frame()
    _, evidence = _preprocess_bgr_frame(source_frame)
    import cv2
    import numpy as np

    fake_vae_codes = list(range(336))
    preprocess_document = {
        "schema_version": SCHEMA_VERSION,
        "fixture_version": "person-a-phase3-preprocessing-golden-v1.0",
        "source_revision": PINNED_SOURCE_REVISION,
        "source_file": "mineworld.py",
        "source_blob_sha256": MINEWORLD_PREPROCESS_BLOB_SHA256,
        "preprocessing_profile": PREPROCESSING_PROFILE,
        "source_fixture": {
            "generator": (
                "uint8 BGR[y,x] = ((x+2y)%256, (3x+y)%256, (x XOR y)%256)"
            ),
            "shape": list(evidence["source_shape"]),
            "dtype": evidence["source_dtype"],
            "sha256": evidence["source_sha256"],
        },
        "operation": {
            "color_conversion": "BGR_TO_RGB",
            "resize": {"width": 384, "height": 224},
            "interpolation": "cv2.INTER_LINEAR",
            "layout": "CHW",
            "normalization": VIDEO_PREPROCESSING_NORMALIZATION,
        },
        "expected_output": {
            "shape": list(evidence["output_shape"]),
            "dtype": evidence["output_dtype"],
            "sha256": evidence["output_sha256"],
            "statistics": evidence["statistics"],
        },
        "dependency_versions": {
            "numpy": np.__version__,
            "opencv": cv2.__version__,
        },
        "visual_code_boundary": {
            "expected_count": 336,
            "cpu_fake_codes": fake_vae_codes,
            "cpu_fake_codes_sha256": hashlib.sha256(
                canonical_json_bytes(fake_vae_codes)
            ).hexdigest(),
            "local_evidence": "CPU fake tokenizer only",
            "real_vae_certification": "pending later GPU certification",
        },
    }
    _write_json(args.action_output, action_document)
    _write_json(args.preprocess_output, preprocess_document)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
